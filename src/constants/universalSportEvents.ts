/**
 * Get all available event definitions for a given sport
 */
export function getSportEvents(sport: SportType | string): SportEventDefinition[] {
  const normalized = (sport || 'CRICKET').toUpperCase() as SportType;
  return UNIVERSAL_SPORT_EVENTS_MAP[normalized] || UNIVERSAL_SPORT_EVENTS_MAP.CRICKET;
}

/**
 * Get visual design & styling information for any sport and event type
 */
export function getSportEventVisualInfo(
  sport: SportType | string,
  eventType: string
): SportVisualInfo {
  const events = getSportEvents(sport);
  const normType = (eventType || '').toUpperCase().trim();

  const found = events.find(
    (e) =>
      e.eventType.toUpperCase() === normType ||
      e.shortName.toUpperCase() === normType ||
      e.id.toUpperCase().endsWith(`_${normType.toLowerCase()}`)
  );

  if (found) {
    return {
      tag: found.eventType,
      badgeText: found.badgeText,
      defaultTitle: found.defaultTitle,
      defaultSubtitle: found.defaultSubtitle,
      defaultMessage: found.defaultMessage || 'Official match scoring event registered',
      primaryColor: found.primaryColor,
      secondaryColor: found.secondaryColor,
      accentGlow: found.accentGlow,
      gradientBackground: `linear-gradient(135deg, ${found.primaryColor}f0 0%, ${found.secondaryColor}fa 100%)`,
      badgeBg: found.badgeBg,
      badgeBorder: found.badgeBorder,
      badgeTextColor: found.badgeTextColor,
      iconType: found.iconType,
      priority: found.defaultPriority,
      durationSeconds: found.defaultDuration,
    };
  }

  // Fallback styling
  return {
    tag: eventType || 'EVENT',
    badgeText: 'LIVE',
    defaultTitle: (eventType || 'LIVE EVENT').replace(/_/g, ' '),
    defaultSubtitle: 'Match Play Event',
    defaultMessage: 'Official match play action registered in scoring system',
    primaryColor: '#0284c7',
    secondaryColor: '#0369a1',
    accentGlow: 'rgba(2, 132, 199, 0.7)',
    gradientBackground: 'linear-gradient(135deg, rgba(2, 132, 199, 0.95) 0%, rgba(3, 105, 161, 0.98) 100%)',
    badgeBg: '#082f49',
    badgeBorder: '#38bdf8',
    badgeTextColor: '#ffffff',
    iconType: 'ALERT',
    priority: 50,
    durationSeconds: 3.5,
  };
}
